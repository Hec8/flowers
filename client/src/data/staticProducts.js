export const ALL_STATIC_PRODUCTS = [
  ...INDOOR_PLANTS,
  ...OUTDOOR_PLANTS,
  ...FLOWERS,
  ...HOME_DECO,
  ...GARDENING,
  ...ENGRAIS,
];

/** Retourne les produits statiques pour une catégorie / productType / subcategory */
export function getStaticProducts({ category = '', productType = '', subcategory = '' } = {}) {
  if (!category && !productType && !subcategory) return ALL_STATIC_PRODUCTS;

  return ALL_STATIC_PRODUCTS.filter((p) => {
    // Page Plantes : intérieur / extérieur
    if (category === 'plantes') {
      if (productType === 'INTERIOR') return INDOOR_PLANTS.some((x) => x.id === p.id);
      if (productType === 'EXTERIOR') return OUTDOOR_PLANTS.some((x) => x.id === p.id);
      return INDOOR_PLANTS.some((x) => x.id === p.id);
    }

    const catMatch = category ? p.category?.slug === category : true;
    const typeMatch = productType ? p.productType === productType : true;
    const subMatch = subcategory ? p.subcategory === subcategory : true;
    return catMatch && typeMatch && subMatch;
  });
}

/** Retourne un produit statique par slug */
export function getStaticProductBySlug(slug) {
  return ALL_STATIC_PRODUCTS.find((p) => p.slug === slug) || null;
}

/**
 * Combine une liste de produits statiques (prioritaires) avec des produits
 * issus de l'API.
 *
 * Règles :
 *  - Si un slug statique a un équivalent en DB  → on garde l'ID DB (commandable)
 *    mais TOUTES les données d'affichage viennent du statique (images Vite,
 *    descriptions riches, careTips, bienfaits…).
 *  - Si le produit statique n'est pas encore en DB → conservé tel quel (s-xx-n).
 *  - Les produits API sans slug statique (créés depuis le dashboard) s'ajoutent à la fin.
 *
 * @param {Array} staticList  - produits statiques (déjà filtrés pour la page)
 * @param {Array} apiList     - produits reçus de l'API
 * @returns {Array}
 */
export function combineWithStatic(staticList, apiList) {
  const apiBySlug = {};
  (apiList || []).forEach((p) => { apiBySlug[p.slug] = p; });

  // Statiques enrichis avec l'ID DB si disponible
  const merged = staticList.map((staticProd) => {
    const dbProd = apiBySlug[staticProd.slug];
    if (dbProd) {
      // ID DB pour que le checkout fonctionne ; display data 100 % statique
      return { ...staticProd, id: dbProd.id, _synced: true };
    }
    return staticProd;
  });

  // Produits API qui n'ont pas d'équivalent statique (ajoutés via dashboard)
  const staticSlugs = new Set(staticList.map((p) => p.slug));
  const extras = (apiList || []).filter((p) => !staticSlugs.has(p.slug));

  return [...merged, ...extras];
}

